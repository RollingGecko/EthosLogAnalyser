# -*- coding: utf-8 -*-
"""Marks a CI build as a test build.

Computes the build tag of a test build and writes it into ``src/ethosloganalyser/_build_tag.py``, which the
app reads (see ``ethosloganalyser/buildinfo.py``). Release builds from a version tag do not call this script,
so they carry no build tag. The repository (``__init__.py``) is never changed.

Build tags (PEP 440 local version labels):
- pull request 12, commit abc1234...  ->  pr12.abc1234
- any other branch, e.g. feature/x    ->  feature.x.abc1234

Usage (GitHub Actions):
    python scripts/set_build_tag.py --pr 12 --sha <commit> --github-output "$GITHUB_OUTPUT"
    python scripts/set_build_tag.py --ref feature/x --sha <commit> --github-output "$GITHUB_OUTPUT"

Writes these outputs: tag, version (e.g. 0.3.0+pr12.abc1234), exe (file name of the test EXE, e.g.
EthosLogAnalyser-0.3.0-pr12-abc1234.exe) and artifact (the same without .exe). Only the Python standard library
is needed.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from release_check import INIT_FILE, read_version  # noqa: E402

TAG_FILE = INIT_FILE.parent / "_build_tag.py"
TAG_PATTERN = re.compile(r"^[a-z0-9]+(\.[a-z0-9]+)*$")     # same as ethosloganalyser.buildinfo.TAG_PATTERN


def make_tag(sha, pr=None, ref=None):
    """Build tag from the pull-request number or the branch name and the commit."""
    sha7 = (sha or "").strip().lower()[:7]
    if not re.fullmatch(r"[0-9a-f]{7}", sha7):
        raise ValueError(f"invalid commit sha: {sha!r}")
    if pr:
        if not str(pr).isdigit():
            raise ValueError(f"invalid pull request number: {pr!r}")
        prefix = f"pr{int(pr)}"
    else:
        prefix = ".".join(p for p in re.split(r"[^a-z0-9]+", (ref or "").lower()) if p)[:40].strip(".") or "branch"
    tag = f"{prefix}.{sha7}"
    if not TAG_PATTERN.match(tag):
        raise ValueError(f"invalid build tag: {tag!r}")
    return tag


def exe_name(version, tag):
    """File name of the test EXE: EthosLogAnalyser-<version>-<tag with dashes>.exe."""
    return f"EthosLogAnalyser-{version}-{tag.replace('.', '-')}.exe"


def module_text(tag):
    return ('# Generated by scripts/set_build_tag.py during a CI test build. Do not commit.\n'
            f'BUILD_TAG = "{tag}"\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sha", required=True, help="commit the build is made from")
    ap.add_argument("--pr", default="", help="pull request number (empty for a branch build)")
    ap.add_argument("--ref", default="", help="branch name (used without --pr)")
    ap.add_argument("--github-output", default="", help="file to append the step outputs to ($GITHUB_OUTPUT)")
    args = ap.parse_args(argv)
    try:
        tag = make_tag(args.sha, pr=args.pr or None, ref=args.ref)
    except ValueError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1
    version = read_version(INIT_FILE.read_text(encoding="utf-8"))
    TAG_FILE.write_text(module_text(tag), encoding="utf-8")
    exe = exe_name(version, tag)
    out = {"tag": tag, "version": f"{version}+{tag}", "exe": exe, "artifact": exe[:-len(".exe")]}
    for k, v in out.items():
        print(f"{k}={v}")
    if args.github_output:
        with open(args.github_output, "a", encoding="utf-8") as fh:
            fh.writelines(f"{k}={v}\n" for k, v in out.items())
    return 0


if __name__ == "__main__":
    sys.exit(main())
