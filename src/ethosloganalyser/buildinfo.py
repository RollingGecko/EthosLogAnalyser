# -*- coding: utf-8 -*-
"""Version shown to the user, and the test-build marker.

Release builds (from a version tag) show the plain version, e.g. ``0.3.0``. Test builds made by the CI for a
pull request or a branch carry a build tag, e.g. ``0.3.0+pr12.abc1234``, and the app marks itself as a test
version in the window title and in the *About* box.

The build tag is not stored in the repository: the CI writes it into the generated module ``_build_tag.py``
(see ``scripts/set_build_tag.py``) right before it builds the EXE. Without that module (source checkout,
release build) the build tag is empty.
"""

import re

from . import __version__

try:
    from ._build_tag import BUILD_TAG          # generated by the CI for test builds, not in git
except ImportError:                             # pragma: no cover - depends on the build
    BUILD_TAG = ""

# PEP 440 local version label: lowercase letters, digits and dots, starting and ending alphanumerically
TAG_PATTERN = re.compile(r"^[a-z0-9]+(\.[a-z0-9]+)*$")


def build_tag(tag=None):
    """The build tag of this build ('' for a release build); tag overrides it (for tests)."""
    return BUILD_TAG if tag is None else tag


def is_test_build(tag=None):
    return bool(build_tag(tag))


def full_version(tag=None):
    """Version including the build tag, e.g. '0.3.0+pr12.abc1234' (test build) or '0.3.0' (release)."""
    t = build_tag(tag)
    return f"{__version__}+{t}" if t else __version__


def window_title(tag=None):
    """Title of the main window; test builds say so first."""
    from .i18n import tr
    if is_test_build(tag):
        return tr("TESTVERSION {version} – EthosLogAnalyser – nicht für den normalen Gebrauch",
                  version=full_version(tag))
    return tr("EthosLogAnalyser {version} – Flug- und Akku-Analyse (FrSky Ethos Logs)", version=full_version(tag))


def about_lines(tag=None):
    """[(kind, text)] for the About box: kind 'version', 'test' or 'info'."""
    from .i18n import tr
    lines = [("version", tr("EthosLogAnalyser, Version {version}", version=full_version(tag)))]
    if is_test_build(tag):
        lines.append(("test", tr("Testversion ({tag}) aus der automatischen Prüfung eines Pull-Requests bzw. "
                                 "Branches – zum Abnahmetest, kein Release.", tag=build_tag(tag))))
    lines.append(("info", tr("Quellcode, Releases und Anleitung: github.com/RollingGecko/EthosLogAnalyser")))
    return lines
